"""Generate browser allowlist code from the shared JSON; does not verify ownership."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
path = ROOT / 'extension/data/website_allowlist.json'
doc = json.loads(path.read_text(encoding='utf-8'))
hosts = [entry['hostname'] for entry in doc['entries']]
if len(hosts) != len(set(hosts)):
    raise ValueError('Duplicate hostname in allowlist')
for entry in doc['entries']:
    if entry['scope'] != 'exact' or not entry['hostname'] or '/' in entry['hostname']:
        raise ValueError('Only exact hostnames are supported')
(path.with_suffix('.js')).write_text('/* Generated by scripts/sync_allowlist.py. */\nself.PhishermanWebsiteAllowlist = ' + json.dumps(doc) + ';\n', encoding='utf-8')
print(f'Synchronized {len(hosts)} hostnames ({doc["version"]})')
