"""Generate the toolbar popup from the dark side-panel workspace; one UI source."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / 'extension/sidepanel/panel.html'
target = ROOT / 'extension/popup/popup.html'
html = source.read_text(encoding='utf-8')
html = html.replace('<body>', '<body data-view="popup">')
html = html.replace('href="panel.css"', 'href="../sidepanel/panel.css"')
html = html.replace('src="panel.js"', 'src="../sidepanel/panel.js"')
html = html.replace('src="workspace.js"', 'src="../sidepanel/workspace.js"')
html = '<!-- Generated by scripts/sync_popup.py; edit sidepanel/panel.html. -->\n' + html
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(html, encoding='utf-8')
print('Toolbar popup synchronized with the dark side-panel workspace')
